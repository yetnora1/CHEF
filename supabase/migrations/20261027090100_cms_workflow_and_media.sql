-- =============================================================================
-- Chief Harena · Stage 3 · Content workflow, translation review, audit, media
-- =============================================================================
-- Shared by every content type (services here; menu, gallery, journal and pages
-- in the next migration):
--   * publication workflow: draft ⇄ in_review → published → archived
--   * optimistic concurrency: `version` increases on every update
--   * Amharic review: an Amharic translation can be published only after a
--     staff member confirms that a fluent speaker reviewed it; changing the text
--     clears that confirmation (docs/LOCALIZATION.md)
--   * audit: every create, update, status change and delete is logged without
--     content (entity, locale, status change, names of changed fields)
-- Media: rows describe images stored in the private Supabase Storage bucket
-- `media` (policies in 20261027090400). Paths are generated by the server and
-- validated here; binaries never live in content rows.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Workflow helpers
-- -----------------------------------------------------------------------------

-- Replaces the Stage 1 rule (same function, so existing triggers keep using it):
--   * creating or editing draft / in-review rows, and moving between those two
--     states: the table's write policy (content.write or translations.write)
--   * publishing, unpublishing, archiving, restoring, and editing a published
--     or archived row: content.publish
-- Contexts without an end-user identity (migrations, seed) are trusted.
create or replace function private.enforce_publish_permission()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  restricted constant public.publication_status[] :=
    array['published', 'archived']::public.publication_status[];
begin
  if (select auth.uid()) is null then
    return new;
  end if;

  if (tg_op = 'INSERT' and new.status = any (restricted))
     or (tg_op = 'UPDATE' and (old.status = any (restricted) or new.status = any (restricted))) then
    if not private.has_permission('content.publish') then
      raise exception 'Not authorized to change published content' using errcode = '42501';
    end if;
  end if;

  return new;
end;
$$;

-- Optimistic concurrency: writers send the version they edited; a stale write
-- matches no row. Clients cannot set it (no column privilege).
create function private.bump_version()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.version := old.version + 1;
  return new;
end;
$$;

-- BEFORE INSERT OR UPDATE on translation tables. Trigger arguments name the
-- text columns whose change invalidates a review. `language_reviewed_at` is
-- stamped here (clients only signal confirm = any value, withdraw = null).
-- Amharic content is drafted without a native speaker today
-- (docs/LOCALIZATION.md): it needs an explicit review confirmation before
-- publication. The rule is inline because the trigger runs as the caller.
create function private.enforce_language_review()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  text_column text;
  text_changed boolean := false;
  requires_review boolean;
begin
  requires_review := new.locale = 'am';

  if tg_op = 'UPDATE' then
    foreach text_column in array tg_argv loop
      if (to_jsonb(new) -> text_column) is distinct from (to_jsonb(old) -> text_column) then
        text_changed := true;
      end if;
    end loop;
  end if;

  if not requires_review then
    new.language_reviewed_at := null;
    new.language_reviewed_by := null;
  elsif tg_op = 'INSERT' or new.language_reviewed_at is distinct from old.language_reviewed_at then
    -- An explicit confirmation or withdrawal in this write.
    if new.language_reviewed_at is not null then
      new.language_reviewed_at := now();
      new.language_reviewed_by := (select auth.uid());
    else
      new.language_reviewed_by := null;
    end if;
  elsif text_changed then
    -- Changed text has not been reviewed.
    new.language_reviewed_at := null;
    new.language_reviewed_by := null;
  end if;

  if (to_jsonb(new) ->> 'status') = 'published' and requires_review and new.language_reviewed_at is null then
    raise exception 'This translation must be confirmed as reviewed by a fluent speaker before it is published'
      using errcode = 'P0001', hint = 'review_required';
  end if;

  return new;
end;
$$;

-- AFTER INSERT OR UPDATE OR DELETE on content and media tables.
-- Arguments: target type, then the column holding the entity id.
-- Audit entries never contain content: only identifiers, the locale, status
-- changes and the names of changed fields.
create function private.audit_content()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_type constant text := tg_argv[0];
  prefix constant text := case when target_type like 'media%' then 'media' else 'content' end;
  old_row jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  new_row jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  row_data jsonb := coalesce(new_row, old_row);
  changed text[];
  action text;
  details jsonb := '{}'::jsonb;
begin
  if tg_op = 'UPDATE' then
    select coalesce(array_agg(n.key order by n.key), '{}') into changed
    from jsonb_each(new_row) n
    where n.key not in ('updated_at', 'updated_by', 'version', 'language_reviewed_by')
      and (old_row -> n.key) is distinct from n.value;
    if cardinality(changed) = 0 then
      return null;
    end if;
    details := jsonb_build_object('fields', to_jsonb(changed));
  end if;

  action := case
    when tg_op = 'INSERT' then prefix || '.created'
    when tg_op = 'DELETE' then prefix || '.deleted'
    when target_type = 'media_asset' and (old_row ->> 'status') = 'pending' and (new_row ->> 'status') = 'ready'
      then 'media.uploaded'
    when target_type = 'media_asset' and (old_row ->> 'storage_path') is not null
         and (old_row ->> 'storage_path') is distinct from (new_row ->> 'storage_path')
      then 'media.replaced'
    when (old_row ->> 'status') is distinct from (new_row ->> 'status') then prefix || '.status_changed'
    else prefix || '.updated'
  end;

  if row_data ? 'status' and target_type <> 'media_asset' then
    details := details || jsonb_build_object('status', row_data ->> 'status');
    if tg_op = 'UPDATE' and (old_row ->> 'status') is distinct from (new_row ->> 'status') then
      details := details || jsonb_build_object('from', old_row ->> 'status');
    end if;
  end if;
  if row_data ? 'locale' then
    details := details || jsonb_build_object('locale', row_data ->> 'locale');
  end if;
  if row_data ? 'language_reviewed_at' and tg_op = 'UPDATE'
     and (old_row -> 'language_reviewed_at') is distinct from (new_row -> 'language_reviewed_at') then
    details := details || jsonb_build_object(
      'review', case when (new_row ->> 'language_reviewed_at') is null then 'cleared' else 'confirmed' end);
  end if;

  insert into public.audit_logs (actor_id, action, target_type, target_id, details)
  values ((select auth.uid()), action, target_type, row_data ->> tg_argv[1], details);
  return null;
end;
$$;

-- -----------------------------------------------------------------------------
-- 2. Media assets (images in Supabase Storage)
-- -----------------------------------------------------------------------------
create table public.media_assets (
  id uuid primary key default gen_random_uuid(),
  -- pending: reserved, no finished upload yet; ready: storage_path holds the file
  status text not null default 'pending'
    constraint media_assets_status_valid check (status in ('pending', 'ready')),
  title text not null
    constraint media_assets_title_length check (char_length(btrim(title)) between 1 and 200),
  -- Photographer or source, shown with the image where credits are displayed.
  credit text constraint media_assets_credit_length check (char_length(credit) <= 200),
  -- The current file and, during an upload or replacement, the reserved target.
  -- Names are generated by the server: assets/<asset id>/<32 random hex>.<ext>
  storage_path text constraint media_assets_storage_path_unique unique,
  pending_path text constraint media_assets_pending_path_unique unique,
  -- Describe the current file (storage_path).
  mime_type text constraint media_assets_mime_valid check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  byte_size integer constraint media_assets_size_range check (byte_size between 1 and 10485760),
  width integer constraint media_assets_width_range check (width between 1 and 8000),
  height integer constraint media_assets_height_range check (height between 1 and 8000),
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id) on delete set null,
  constraint media_assets_storage_path_format
    check (storage_path ~ ('^assets/' || id::text || '/[0-9a-f]{32}\.(jpg|png|webp)$')),
  constraint media_assets_pending_path_format
    check (pending_path ~ ('^assets/' || id::text || '/[0-9a-f]{32}\.(jpg|png|webp)$')),
  constraint media_assets_extension_matches_type check (
    storage_path is null or mime_type = case substring(storage_path from '\.([a-z]+)$')
      when 'jpg' then 'image/jpeg' when 'png' then 'image/png' when 'webp' then 'image/webp' end
  ),
  constraint media_assets_ready_complete check (
    status <> 'ready'
    or (storage_path is not null and mime_type is not null and byte_size is not null
        and width is not null and height is not null)
  )
);

create index media_assets_updated_at_idx on public.media_assets (updated_at desc);

comment on table public.media_assets is
  'Images in the private Storage bucket "media". Public only while published content uses them.';

-- Alt text per locale. No publication status of its own: it is shown wherever
-- the image is shown; unreviewed Amharic alt text falls back to English.
create table public.media_asset_translations (
  asset_id uuid not null references public.media_assets (id) on delete cascade,
  locale public.locale_code not null,
  alt_text text not null
    constraint media_asset_translations_alt_length check (char_length(btrim(alt_text)) between 1 and 300),
  language_reviewed_at timestamptz,
  language_reviewed_by uuid references auth.users (id) on delete set null,
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id) on delete set null,
  primary key (asset_id, locale)
);

-- Upload lifecycle rules for API callers (BEFORE INSERT OR UPDATE):
--   * a new asset starts as pending, without a file
--   * storage_path changes only by finalising the reserved upload, and only once
--     the object exists in Storage (visible to this media.write holder)
--   * a ready asset never returns to pending
create function private.enforce_media_asset_lifecycle()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (select auth.uid()) is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'pending' or new.storage_path is not null then
      raise exception 'A new image starts as a pending upload' using errcode = '22023';
    end if;
    return new;
  end if;

  if old.status = 'ready' and new.status <> 'ready' then
    raise exception 'A finished image cannot return to pending' using errcode = '22023';
  end if;

  if new.storage_path is distinct from old.storage_path then
    if new.storage_path is null or new.storage_path is distinct from old.pending_path
       or new.pending_path is not null then
      raise exception 'The file can only change by completing the reserved upload' using errcode = '22023';
    end if;
    if not exists (
      select 1 from storage.objects o where o.bucket_id = 'media' and o.name = new.storage_path
    ) then
      raise exception 'The uploaded file was not found' using errcode = '22023', hint = 'upload_missing';
    end if;
  end if;

  return new;
end;
$$;

create trigger media_assets_lifecycle
  before insert or update on public.media_assets
  for each row execute function private.enforce_media_asset_lifecycle();

